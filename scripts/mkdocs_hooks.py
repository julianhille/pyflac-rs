"""MkDocs hooks: point "Edit on GitHub" at the file to edit.

Some pages are not written in docs/: the home page is a copy of the README and
the third-party page is generated by scripts/licenses.py.
"""

# Pages whose source is elsewhere in the repository, relative to edit_uri.
SOURCES = {
    "index.md": "README.md",
    "third-party.md": "scripts/licenses.py",
}


def on_files(files, config):
    for file in files:
        file.edit_uri = SOURCES.get(file.src_uri, "docs/" + file.src_uri)
    return files
